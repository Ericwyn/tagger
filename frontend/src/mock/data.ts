type TrackSeed = Partial<Track> & Pick<Track, 'id' | 'fileName' | 'relativePath' | 'folderId' | 'title' | 'artists' | 'album'>;

function track(seed: TrackSeed): Track {
  const format = seed.format ?? (seed.fileName.endsWith('.mp3') ? 'mp3' : 'flac');
  return {
    id: seed.id,
    fileName: seed.fileName,
    relativePath: seed.relativePath,
    folderId: seed.folderId,
    format,
    sizeBytes: seed.sizeBytes ?? (format === 'mp3' ? 10_980_000 : 31_420_000),
    durationSeconds: seed.durationSeconds ?? 248,
    title: seed.title,
    artists: seed.artists,
    album: seed.album,
    albumArtists: seed.albumArtists ?? seed.artists,
    trackNumber: seed.trackNumber,
    trackTotal: seed.trackTotal,
    discNumber: seed.discNumber ?? 1,
    discTotal: seed.discTotal ?? 1,
    year: seed.year,
    genres: seed.genres ?? ['流行'],
    lyrics: seed.lyrics ?? '',
    artworkCount: seed.artworkCount ?? 1,
    coverTone: seed.coverTone ?? 'vermilion',
    health: seed.health ?? 'complete',
    properties: seed.properties ?? (format === 'mp3' ? mp3 : lossless),
    writable: seed.writable ?? true,
    revision: seed.revision ?? `rev-${seed.id}-1`,
    modifiedAt: seed.modifiedAt ?? '2026-08-18 21:42',
  };
}

